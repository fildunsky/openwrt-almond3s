#!/bin/sh
# Экран уже показывает «Выключаю питание...» (action_splash из интерфейса).
# Раньше первой же строкой шёл dim 0 - подсветка гасла мгновенно, и это
# сообщение никто не видел, а завершалось всё белой вспышкой обесточивания.
# Теперь: дать прочитать сообщение при живой подсветке, потом плавно в
# темноту и уложить панель в сон - тьма вместо белой вспышки.
sleep 1
almond3s-lcd dim 0 >/dev/null 2>&1        # подсветку в ноль - чистая темнота
almond3s-lcd panel 0x28 >/dev/null 2>&1   # Display OFF
almond3s-lcd panel 0x10 >/dev/null 2>&1   # Sleep In - панель в тихое состояние
sleep 1                                    # дать командам уйти на панель до kill
sync
poweroff
