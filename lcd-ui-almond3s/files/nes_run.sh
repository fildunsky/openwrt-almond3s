#!/bin/sh
# nes_run.sh <rom> — запуск эмулятора NES на весь экран.
#
# UI гасим: он держит /dev/lcd и первым разбирает касания - при живом UI кнопки
# в игре просто не доходят до эмулятора. По выходу поднимаем обратно.
#
# Блокировка обязательна: без неё вторая копия скрипта (или осиротевшая от
# прошлого запуска) доигрывает свою последнюю строку и поднимает UI поверх
# работающей игры - касания начинают уезжать в меню.

ROM="$1"
# Какое ядро запускать - выбирается в «Игры → Настройки» и лежит тут же файлом.
# QuickNES точнее держит игры с маппером MMC3 (Super Mario Bros 3 и подобные),
# InfoNES знает больше мапперов. Не подошло - переключаешься одним тапом.
CORE=$(cat /etc/almond3s/nes_core 2>/dev/null)
if [ "$CORE" = quicknes ] && [ -x /usr/libexec/almond3s/nes-quick ]; then
	NES=/usr/libexec/almond3s/nes-quick
else
	NES=/usr/libexec/almond3s/nes
fi

[ -x "$NES" ] || exit 1
[ -f "$ROM" ] || exit 1

# Один сеанс за раз - через блокировку, которую держим ВСЁ время работы.
#
# Проверка «а не запущен ли уже эмулятор» тут не годится: между ней и реальным
# стартом проходит больше секунды (остановка UI и пауза), и два запуска подряд
# оба её проходят - получаются две копии, которые рисуют в панель поочерёдно и
# делят между собой касания.
#
# busybox-овский flock не понимает форму с номером дескриптора (принимает его за
# имя файла), поэтому используем форму «файл + команда»: перезапускаем сам себя
# под блокировкой. Не досталась - молча выходим, первый сеанс продолжает играть.
LOCK=/var/lock/almond3s-nes.lock
if [ -z "$NES_LOCK_HELD" ]; then
	mkdir -p /var/lock
	NES_LOCK_HELD=1
	export NES_LOCK_HELD
	exec flock -n "$LOCK" "$0" "$@"
fi

/etc/init.d/almond3s-lcd stop >/dev/null 2>&1
sleep 1

# Служба гасит ВСЮ связку, включая демон касаний almond3s-lcd - а именно он
# опрашивает тачскрин и пишет /tmp/.lcd_touch. Без него в игре не работает ни
# одна кнопка и из неё не выйти. Поэтому демон поднимаем обратно отдельно.
/usr/bin/almond3s-lcd daemon_fg >/dev/null 2>&1 &
TOUCHD=$!
sleep 1

# Залежавшееся касание эмулятор прочитал бы первым же кадром - и, попади оно в
# зону EXIT, игра закрылась бы сразу после старта.
rm -f /tmp/.lcd_touch /tmp/.lcd_touch.move

"$NES" "$ROM" >/dev/null 2>/tmp/nes.log

# Демон касаний снимаем поимённо: по PID не всегда получается (setsid уводит
# процесс), а лишняя копия потом даёт ДВОЙНЫЕ нажатия в меню - каждое касание
# записывают оба демона.
kill $TOUCHD 2>/dev/null
for q in $(ps w | grep "[a]lmond3s-lcd daemon" | awk "{print \$1}"); do kill $q 2>/dev/null; done
sleep 1
rm -f /tmp/.lcd_touch /tmp/.lcd_touch.move
/etc/init.d/almond3s-lcd start >/dev/null 2>&1

# Возвращаем туда, откуда игру и запускали - в список игр, а не на стартовую
# страницу. UI читает этот файл при старте, но ему нужно успеть подняться.
sleep 4
echo games > /tmp/.lcd_goto
exit 0
