# ё и Ё в haxrcorp4089 отсутствуют вовсе - рисуем в его стиле
MISSING = {
0x2D: (1,3,["#####"]),
0x3A: (5,0,["##","##","..","##","##"]),
0x451: (7,0,["#..#","....",".##.","#..#","####","#...",".##."]),
0x401: (9,0,["#..#","....","####","#...","#...","###.","#...","#...","####"]),
}

NARROW = {
ord('i'): (7,0,[".#.","...","##.",".#.",".#.",".#.","###"]),
ord('I'): (7,0,["###",".#.",".#.",".#.",".#.",".#.","###"]),
ord('l'): (7,0,["##.",".#.",".#.",".#.",".#.",".#.","###"]),
ord('j'): (9,-2,["..#","...","..#","..#","..#","..#","..#","#.#",".#."]),
ord('f'): (7,0,[".##",".#.","###",".#.",".#.",".#.",".#."]),
ord('1'): (7,0,[".#.","##.",".#.",".#.",".#.",".#.","###"]),
}

def apply(glyphs, table):
    for cp, (h, y, art) in table.items():
        rows = [[1 if c == '#' else 0 for c in line] for line in art]
        w = len(art[0])
        assert len(art) == h and all(len(r) == w for r in rows), hex(cp)
        g = glyphs[str(cp)]
        g["rows"] = rows; g["w"] = w; g["h"] = h; g["y"] = y

glyphs = json.load(open("hax_preview.json"))
for cp in MISSING:
    glyphs.setdefault(str(cp), {"w":0,"h":0,"x":0,"y":0,"adv":6,"rows":[]})
apply(glyphs, WIDE)
apply(glyphs, NARROW)
apply(glyphs, MISSING)
for cp, g in glyphs.items():
    g["adv"] = 6
    g["x"] = (5 - g["w"]) // 2   # чернила по центру 5 колонок, как в 5x7

# двоеточие - узкая клетка 4: в часах «07:31» полная клетка 6 вокруг
# однопиксельных точек читалась как пробел
g = glyphs[str(0x3A)]
g["adv"] = 5; g["x"] = 1
json.dump(glyphs, open("hax_mono.json", "w"))
print(f"готово: {len(WIDE)} широких + {len(NARROW)} узких перерисовано, все x=0")
